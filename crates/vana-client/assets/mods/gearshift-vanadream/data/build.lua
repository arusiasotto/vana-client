-- Rebuilds this folder's data files from the Vanadreams server tables vanagear ships (its data/ folder):
--   luajit build.lua <path to vanagear/data> [out folder, default: here]
-- items.lua      id = "level|jobs|slot|skill|delay|dmg|mods|pets", one short string each (decoded when asked for)
-- mods.lua       the server mod id = name
-- slotblocks.lua item id = the extra slots it takes (a tunic takes the head's, so nothing is worn there with it)
-- Not run by the client.

local from = assert(arg[1], "usage: luajit build.lua <vanagear/data> [out]")
local out = arg[2] or (arg[0]:match("^(.*)[/\\][^/\\]*$") or ".")

local function load(name)
  return assert(loadfile(from .. "/" .. name .. ".lua"))()
end

local function sorted(t)
  local keys = {}
  for k in pairs(t) do keys[#keys + 1] = k end
  table.sort(keys)
  return keys
end

local function pairs_text(t)
  local list = {}
  for _, k in ipairs(sorted(t)) do list[#list + 1] = k .. "=" .. t[k] end
  return table.concat(list, ",")
end

local function write(name, header, lines)
  local f = assert(io.open(out .. "/" .. name .. ".lua", "w"))
  f:write(header, "\nlocal t = {}\n", table.concat(lines, "\n"), "\nreturn t\n")
  f:close()
end

local items = load("items")
local lines = {}
for _, id in ipairs(sorted(items)) do
  local it = items[id]
  local pets = {}
  for _, p in ipairs(sorted(it.pet or {})) do
    for _, k in ipairs(sorted(it.pet[p])) do pets[#pets + 1] = p .. "." .. k .. "=" .. it.pet[p][k] end
  end
  lines[#lines + 1] = ("t[%d]=%q"):format(id, table.concat({
    it.level or 0, it.jobs or 0, it.slot or 0, it.skill or "", it.delay or "", it.dmg or "",
    pairs_text(it.mods or {}), table.concat(pets, ","),
  }, "|"))
end
write("items", "-- Equippable items by id: \"level|jobs|slot|skill|delay|dmg|mods|pets\" from the Vanadreams server's tables.\n"
  .. "-- jobs and slot are the server's masks (job n is bit n-1; slot s is bit s); mods are mod=value, pets are petType.mod=value.\n"
  .. "-- Generated by build.lua from vanagear's data; rebuild, do not edit.", lines)

local mods = load("mods")
lines = {}
for _, id in ipairs(sorted(mods)) do lines[#lines + 1] = ("t[%d]=%q"):format(id, mods[id]) end
write("mods", "-- The server's mod id = name. Generated by build.lua; rebuild, do not edit.", lines)

local blocks = load("slotblocks")
lines = {}
for _, id in ipairs(sorted(blocks)) do lines[#lines + 1] = ("t[%d]=%d"):format(id, blocks[id]) end
write("slotblocks", "-- Item id = the other slots it takes (server rslot bits). Generated by build.lua; rebuild, do not edit.", lines)
