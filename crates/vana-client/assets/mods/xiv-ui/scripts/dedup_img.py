#!/usr/bin/env python3
"""Suite img/: one path per PNG bytes (except img/panels/*); img/_aliases.lua for legacy paths."""
from __future__ import annotations

import argparse
import hashlib
import re
import shutil
from collections import defaultdict
from pathlib import Path

UI = Path(__file__).resolve().parents[1]
MODULES = UI / "modules"
IMG = UI / "img"
ALIASES = IMG / "_aliases.lua"


def rel_from_img(p: Path) -> str:
    parts = p.parts
    idx = parts.index("img")
    return "/".join(parts[idx + 1 :])


def panel_name(p: Path) -> str:
    parts = p.parts
    i = parts.index("modules")
    return parts[i + 1]


def collect_sources() -> list[Path]:
    return sorted(MODULES.rglob("*.png"))


def img_key(p: Path) -> str:
    return "img/" + p.relative_to(IMG).as_posix()


def is_panel_path(p: Path) -> bool:
    return "panels" in p.relative_to(IMG).parts


def pick_canonical(paths: list[Path]) -> Path:
    def score(p: Path) -> tuple:
        s = p.relative_to(IMG).as_posix()
        return (len(s), s)

    return min(paths, key=score)


def write_aliases(aliases: dict[str, str]) -> None:
    lines = ["-- Generated by scripts/dedup_img.py; do not edit.", "return {"]
    for k in sorted(aliases):
        v = aliases[k]
        lines.append(f'  ["{k}"] = "{v}",')
    lines.append("}")
    ALIASES.write_text("\n".join(lines) + "\n", encoding="utf-8")


def canonicalize_tree() -> tuple[int, int, int]:
    if not IMG.is_dir():
        return 0, 0, 0
    by_hash: dict[str, list[Path]] = defaultdict(list)
    for p in IMG.rglob("*.png"):
        if p.name.startswith("_"):
            continue
        by_hash[hashlib.sha256(p.read_bytes()).hexdigest()].append(p)

    aliases: dict[str, str] = {}
    removed = 0
    for paths in by_hash.values():
        if len(paths) == 1:
            continue
        panel_paths = [p for p in paths if is_panel_path(p)]
        flat_paths = [p for p in paths if not is_panel_path(p)]

        if len(flat_paths) > 1:
            keep = pick_canonical(flat_paths)
            keep_key = img_key(keep)
            for p in flat_paths:
                if p.resolve() == keep.resolve():
                    continue
                aliases[img_key(p)] = keep_key
                p.unlink()
                removed += 1

        if len(panel_paths) > 1:
            keep = pick_canonical(panel_paths)
            keep_key = img_key(keep)
            for p in panel_paths:
                if p.resolve() == keep.resolve():
                    continue
                aliases[img_key(p)] = keep_key
                p.unlink()
                removed += 1
        # img/panels/* overrides are never aliased to flat paths; keep both files if bytes match.

    write_aliases(aliases)
    n = sum(1 for _ in IMG.rglob("*.png"))
    unique = len({hashlib.sha256(p.read_bytes()).hexdigest() for p in IMG.rglob("*.png")})
    return n, unique, removed


def build_from_modules(pngs: list[Path]) -> None:
    if IMG.exists():
        shutil.rmtree(IMG)
    IMG.mkdir(parents=True)

    by_hash: dict[str, list[tuple[str, Path]]] = defaultdict(list)
    for p in pngs:
        rel = rel_from_img(p)
        h = hashlib.sha256(p.read_bytes()).hexdigest()
        by_hash[h].append((rel, p))

    for h, entries in by_hash.items():
        entries = sorted(entries, key=lambda x: (x[0], str(x[1])))
        rels = {rel for rel, _ in entries}
        if len(rels) == 1 and len(entries) > 1:
            rel = next(iter(rels))
            dest = IMG / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(entries[0][1], dest)
            continue
        for rel, src in entries:
            dest = IMG / rel
            if dest.exists():
                if hashlib.sha256(dest.read_bytes()).hexdigest() == h:
                    continue
                dest = IMG / "panels" / panel_name(src) / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dest)

    for p in pngs:
        p.unlink()
    for d in sorted(MODULES.rglob("img"), reverse=True):
        if d.is_dir() and not any(d.iterdir()):
            d.rmdir()


def canonicalize_tree_dry() -> tuple[int, int, int]:
    by_hash: dict[str, list[Path]] = defaultdict(list)
    for p in IMG.rglob("*.png"):
        by_hash[hashlib.sha256(p.read_bytes()).hexdigest()].append(p)
    n = len(list(IMG.rglob("*.png")))
    for paths in by_hash.values():
        flats = [p for p in paths if not is_panel_path(p)]
        if len(flats) > 1:
            return n, len(by_hash), -1
        panels = [p for p in paths if is_panel_path(p)]
        if len(panels) > 1:
            return n, len(by_hash), -1
    return n, len(by_hash), 0


def alias_count() -> int:
    if not ALIASES.is_file():
        return 0
    return len(re.findall(r'\["img/', ALIASES.read_text()))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="exit 1 if dedup needed")
    args = parser.parse_args()

    pngs = collect_sources()
    if pngs:
        build_from_modules(pngs)
        print(f"built from {len(pngs)} module pngs")

    if args.check:
        if not ALIASES.is_file():
            raise SystemExit(1)
        n, unique, bad = canonicalize_tree_dry()
        if bad != 0:
            raise SystemExit(1)
        print(f"ok: {n} png paths, {unique} unique content hashes, {alias_count()} aliases")
        return

    n, unique, removed = canonicalize_tree()
    alias_n = len(re.findall(r'\["img/', ALIASES.read_text())) if ALIASES.is_file() else 0
    print(f"img/: {n} png paths ({unique} unique bytes), removed {removed} flat duplicates")
    print(f"aliases: {alias_n} entries in img/_aliases.lua")


if __name__ == "__main__":
    main()